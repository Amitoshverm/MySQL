-- find avg scores from customers
USE SALESDB;
SELECT * FROM CUSTOMERS;
DELETE FROM CUSTOMERS
WHERE CUSTOMERID = 6;
SELECT 
	CUSTOMERID,
    COALESCE(SCORE, 0),
    SUM(SCORE) OVER() TOTALSCORE,
    2500/5 AS CHECKING,
    1+2,
    'A' + 'B',
    AVG(SCORE) OVER() AVGSCORE,
	AVG(COALESCE(SCORE, 0)) OVER() AVGSCORE2
FROM CUSTOMERS;


-- display the full name of customers in single field by merging their first and last name, and add 10 points to each customers score
SELECT * FROM CUSTOMERS;
SELECT * FROM ORDERS;

SELECT 
	CUSTOMERID,
	-- CONCAT_WS(' ',FIRSTNAME, LASTNAME) AS CUSTOMERNAME,
    CONCAT(FIRSTNAME, ' ', COALESCE(LASTNAME, '')) AS CUSTOMERNAME,
	SCORE,
	COALESCE(SCORE, 0) + 10 AS NEWSCORE
FROM CUSTOMERS;




