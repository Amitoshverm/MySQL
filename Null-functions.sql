-- NULL FUNCTIONS 
-- IFNULL()

SELECT 
*
FROM orders;

SELECT 
	ORDERID,
	SHIPADDRESS,
	IFNULL(SHIPADDRESS, 'UNKNOWN') AS SHIPADDRESS,
	BILLADDRESS,
	IFNULL(BILLADDRESS, 'unknown') AS BillAddress
FROM ORDERS;

SELECT
	SHIPADDRESS,
	BILLADDRESS,
	IFNULL(BILLADDRESS, SHIPADDRESS)
FROM Orders;

-- coalese()

SELECT 
	SHIPADDRESS,
	BILLADDRESS,
	COALESCE(SHIPADDRESS, BILLADDRESS, 'N/A') -- coalesce
FROM ORDERS;








