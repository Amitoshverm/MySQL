-- FIND THE AVERAGE SHIPPING DURATION IN DAYS FOR EACH MONTHS
SELECT * FROM ORDERS;
SELECT 

    MONTH(ORDERDATE) AS ORDERDATE,
    ROUND(AVG(TIMESTAMPDIFF(DAY, ORDERDATE, SHIPDATE)),0) AS AVGDAYS2SHIP
FROM ORDERS
GROUP BY ORDERDATE;

-- FIND THE NUMBER OF DAYS BETWEEN EACH ORDER AND PREVIOUS ORDER
SELECT * FROM ORDERS;
SELECT
	ORDERID,
    LAG(ORDERDATE) OVER (ORDER BY ORDERDATE) AS PREVIOUS_ORDERS,
    ORDERDATE AS CURRENT_ORDER_DATE,
    TIMESTAMPDIFF(DAY, LAG(ORDERDATE) OVER (ORDER BY ORDERDATE), ORDERDATE) AS DAYS_BETWEEEN
FROM ORDERS;

